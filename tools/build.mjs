#!/usr/bin/env node
// Build the Detent site (tools/seo/SEO.md). Node 18+, no dependencies.
//
//   node tools/build.mjs           writes site/: the home, a page per control and per hub, sitemaps, robots.txt, llms.txt, 404.html
//   node tools/build.mjs --check   changes nothing; reports pages that break the SEO rules and output that is out of date
//
// Every page is the same app: src/template.html plus the approved controls, looks and SwiftUI sources taken verbatim
// from src/catalog.html. Each page gets its own head (title, description, canonical, share tags, JSON-LD) and its own
// h1 and copy in static HTML, so search engines read it without running JavaScript. Copy and URLs: tools/seo/site.json.
import { readFileSync, writeFileSync, existsSync, readdirSync, unlinkSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const at = (...p) => join(root, ...p);
const read = p => readFileSync(at(p), 'utf8');
const CHECK = process.argv.includes('--check');
const MARK = '<!-- Generated by tools/build.mjs. Edit src/ or tools/seo/site.json, then run npm run build. -->';
const MARK_TXT = '# Generated by tools/build.mjs. Edit tools/seo/site.json, then run npm run build.';

const cfg = JSON.parse(read('tools/seo/site.json'));
const ORIGIN = cfg.origin.replace(/\/$/, '');
const esc = t => String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const errors = [], warnings = [];

// ── The catalogue: PARTS is a JavaScript literal (it holds arrow functions), so it is evaluated, not parsed. ──
const catalog = read('src/catalog.html');
const blocks = catalog.match(/<script id="src-[a-z0-9-]+">[\s\S]*?<\/script>/g);
const swift = catalog.match(/<script type="text\/plain" id="swift-[a-z0-9-]+">[\s\S]*?<\/script>/g);
const a = catalog.indexOf('  const PARTS = ['), b = catalog.indexOf('\n  ];', a) + '\n  ];'.length;
const partsSrc = catalog.slice(a, b);
const PARTS = new Function(partsSrc + '\nreturn PARTS;')();

const template = read('src/template.html');
const constant = name => new Function(`return ${template.match(new RegExp(`const ${name} = (\\{.*?\\});`))[1]}`)();
const LOOK_NAMES = constant('LOOK_NAMES'), LOOK_LINES = constant('LOOK_LINES');
const ORDER = ['braun', 'nothing', 'index', 'aqua', 'pedal', 'original'];
const sorted = p => [...p.looks].sort((x, y) => ORDER.indexOf(x) - ORDER.indexOf(y));
const attrText = o => Object.entries(o).map(([k, v]) => v === '' ? ` ${k}` : ` ${k}="${esc(v)}"`).join('');
const tag = (p, attrs) => `<${p.tag}${attrText(attrs)}></${p.tag}>`;

// ── Routes: one clean URL per control, permanent once published. ──
for (const p of PARTS) if (!cfg.parts[p.tag]) errors.push(`tools/seo/site.json has no entry for ${p.tag} (${p.name}): give it a slug, title and description`);
for (const t of Object.keys(cfg.parts)) if (!PARTS.some(p => p.tag === t)) warnings.push(`tools/seo/site.json lists ${t}, which is not in PARTS`);
const slugs = new Set();
for (const [t, s] of [...Object.entries(cfg.parts), ...(cfg.hubs || []).map(h => [`hub ${h.slug}`, h])]) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(s.slug)) errors.push(`${t}: slug "${s.slug}" must be lowercase words joined by hyphens`);
  if (['index', '404', 'og', 'api', 'sitemap', 'robots', 'llms', 'favicon'].includes(s.slug)) errors.push(`${t}: slug "${s.slug}" is reserved`);
  if (slugs.has(s.slug)) errors.push(`slug "${s.slug}" is used twice`); slugs.add(s.slug);
}
if (errors.length) finish();

// ── Hubs: a page per group of controls (site.json hubs). One with fewer than MIN_HUB controls is not written. ──
const MIN_HUB = 3;
const HUBS = (cfg.hubs || []).flatMap(h => {
  const parts = PARTS.filter(p => h.match.groups.includes(p.group));
  if (parts.length >= MIN_HUB) return [{ ...h, path: '/' + h.slug, parts }];
  console.log(`note: hub /${h.slug} skipped: it matches ${parts.length} control${parts.length === 1 ? '' : 's'}, fewer than ${MIN_HUB}`);
  return [];
});
const hubOf = p => HUBS.find(h => h.parts.includes(p));

const title = t => `${t} · ${cfg.name}`;
const ROUTES = { '': { path: '/', title: title(cfg.home.title), description: cfg.home.description } };
for (const p of PARTS) { const s = cfg.parts[p.tag], h = hubOf(p); ROUTES[p.tag] = { path: '/' + s.slug, title: title(s.title), description: s.description, ...(h && { hub: h.path }) }; }
for (const h of HUBS) ROUTES[`hub:${h.slug}`] = { path: h.path, title: title(h.title), description: h.description };
const url = path => ORIGIN + path;
const cardFile = name => `og/${name}.png`;
const card = name => existsSync(at('site', cardFile(name))) ? url('/' + cardFile(name)) : null;

// ── Last change, for the sitemap: the newest commit touching what a page is made of. ──
const lastmod = (() => {
  try { return execFileSync('git', ['log', '-1', '--format=%cs', '--', 'src', 'tools/seo/site.json'], { cwd: root, encoding: 'utf8' }).trim() || null; }
  catch { return null; }
})();

// ── Head: the same block on every page. ──
const head = ({ path, title: t, description, image, imageAlt, jsonld }) => [
  `<title>${esc(t)}</title>`,
  `<meta name="description" content="${esc(description)}">`,
  `<link rel="canonical" href="${url(path)}">`,
  `<meta property="og:type" content="website">`,
  `<meta property="og:site_name" content="${esc(cfg.name)}">`,
  `<meta property="og:title" content="${esc(t)}">`,
  `<meta property="og:description" content="${esc(description)}">`,
  `<meta property="og:url" content="${url(path)}">`,
  ...(image ? [
    `<meta property="og:image" content="${image}">`, `<meta property="og:image:width" content="1200">`, `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${esc(imageAlt)}">`, `<meta name="twitter:card" content="summary_large_image">`, `<meta name="twitter:image" content="${image}">`,
  ] : [`<meta name="twitter:card" content="summary">`]),
  `<meta name="detent-signup" content="/api/subscribe">`,
  `<meta name="detent-paths" content="1">`,
  `<script type="application/json" id="detent-routes">${JSON.stringify(ROUTES)}</script>`,
  ...jsonld.map(j => `<script type="application/ld+json">${JSON.stringify(j).replace(/</g, '\\u003c')}</script>`),
].join('\n');

const breadcrumbs = trail => ({ '@context': 'https://schema.org', '@type': 'BreadcrumbList',
  itemListElement: trail.map(([name, path], k) => ({ '@type': 'ListItem', position: k + 1, name, item: url(path) })) });
const org = { '@type': 'Organization', name: cfg.studio.name, url: cfg.studio.url };
const site = { '@type': 'WebSite', name: cfg.name, url: url('/') };
const code = (name, description, path, image) => ({
  '@context': 'https://schema.org', '@type': 'SoftwareSourceCode', name, description, url: url(path), codeRepository: cfg.repo,
  license: 'https://opensource.org/licenses/MIT', programmingLanguage: ['JavaScript', 'Swift'], author: org, isPartOf: site, ...(image && { image }),
});

// ── The app shell: template + controls, as tools/build.py used to make it. ──
let shell = template
  .replace('<!--BLOCKS-->', () => '<!-- The approved Detent controls, verbatim. -->\n' + blocks.join('\n\n') + '\n\n<!-- SwiftUI sources -->\n' + swift.join('\n'))
  .replace('  //PARTS', () => partsSrc)
  .replace(/<meta name="description"[^>]*>\n/, '').replace(/<meta property="og:[a-z]+"[^>]*>\n/g, '')
  .replace('<!--SEO:HUBS-->', () => HUBS.length ? `<span>${HUBS.map(h => `<a href="${h.path}" data-tag="">${esc(h.name)}</a>`).join(' · ')}</span>` : '');
// iOS ignores an SVG touch icon, so the PNGs that tools/seo/og.mjs draws replace it once they exist.
if (existsSync(at('site/apple-touch-icon.png'))) shell = shell.replace(/<link rel="apple-touch-icon" href="data:[^"]*">/, '<link rel="apple-touch-icon" href="/apple-touch-icon.png">');
if (existsSync(at('site/og/favicon-32.png'))) shell = shell.replace(/<link rel="icon" type="image\/svg\+xml"/, m => `<link rel="icon" type="image/png" sizes="32x32" href="/og/favicon-32.png">\n${m}`);
for (const ph of ['<!--BLOCKS-->', '  //PARTS', '<title>Detent</title>', '<!--SEO:GRID-->', '<!--SEO:SHOWPIECE-->', '<!--SEO:HUBS-->', '<main id="detail" hidden></main>'])
  if (!template.includes(ph)) errors.push(`src/template.html is missing ${ph}`);
if (errors.length) finish();

const pageWith = (headHtml, homeHtml, detailHtml) => {
  let page = shell.replace('<title>Detent</title>', () => headHtml)
    .replace(/<main id="home">[\s\S]*?\n  <\/main>/, () => homeHtml)
    .replace('<main id="detail" hidden></main>', () => detailHtml);
  if (!page.trimStart().toLowerCase().startsWith('<!doctype')) page = `<!doctype html>\n<html lang="en">\n${MARK}\n${page}\n</html>\n`;
  return page;
};

// ── Home ──
// The home grid and each hub's grid share this markup: the app paints every .stage[data-i] with PARTS[i] in the chosen look.
const grid = parts => parts.map(p => `
      <div class="plate${['detent-bezel', 'detent-clock'].includes(p.tag) || p.wide ? ' big' : ''}">
        <div class="stage" data-i="${PARTS.indexOf(p)}">${p.kind.toLowerCase() !== p.name.toLowerCase() ? `<span class="tag">${esc(p.kind)}</span>` : ''}${tag(p, p.attrs.light)}</div>
        <a class="cap" href="${ROUTES[p.tag].path}" data-tag="${p.tag}"><h3>${esc(p.name)}</h3><span class="go">↗</span><p>${esc(p.note)}</p></a>
      </div>`).join('') + '\n    ';
const first = PARTS[0], firstHref = ROUTES[first.tag].path;
const homeMain = template.match(/<main id="home">[\s\S]*?\n  <\/main>/)[0]
  .replaceAll('{{START_HREF}}', firstHref).replaceAll('{{START_TAG}}', first.tag).replaceAll('{{START_NAME}}', esc(first.name))
  .replace('<!--SEO:SHOWPIECE-->', () => { const s = PARTS.find(x => x.tag === cfg.home.card.part) || first; return tag(s, { ...s.attrs.light, look: 'braun', mode: 'weighted' }); })
  .replace('<!--SEO:GRID-->', () => grid(PARTS));
const faq = [...homeMain.matchAll(/<details><summary>([\s\S]*?)<\/summary><p>([\s\S]*?)<\/p><\/details>/g)]
  .map(([, q, a]) => ({ q: plain(q), a: plain(a) }));
function plain(html) { return html.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/\s+/g, ' ').trim(); }

const out = new Map();   // path in site/ → contents
const homeCard = card('home');
out.set('index.html', pageWith(head({
  ...ROUTES[''], image: homeCard, imageAlt: `${cfg.name}: ${cfg.home.card.headline} ${cfg.home.card.line}`,
  jsonld: [
    { '@context': 'https://schema.org', ...site, publisher: org, description: cfg.home.description },
    code(cfg.name, cfg.home.description, '/', homeCard),
    { '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: faq.map(f => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } })) },
  ],
}), homeMain, '<main id="detail" hidden></main>'));

// ── One page per control. The static copy here is what the app's renderDetail draws first; the app then takes over. ──
PARTS.forEach((p, i) => {
  const r = ROUTES[p.tag], s = cfg.parts[p.tag], h = hubOf(p);
  const prev = PARTS[(i - 1 + PARTS.length) % PARTS.length], next = PARTS[(i + 1) % PARTS.length];
  const looks = sorted(p);
  const detail = `<main id="detail" data-tag="${p.tag}">
      <nav class="crumbs"><a href="/#components" data-tag="">Components</a><span>›</span>${r.hub ? `<a href="${r.hub}" data-tag="">${esc(p.group)}</a>` : `<span>${esc(p.group)}</span>`}<span>›</span><span>${esc(p.name)}</span></nav>
      <div class="dhead"><h1 tabindex="-1">${esc(p.name)}</h1><p>${esc(p.lede)}</p></div>
      <div id="dview"><div class="preview"><span class="small tl">${esc(p.kind)}</span>${tag(p, { ...p.attrs.light, ...(looks[0] !== p.looks[0] && { look: looks[0] }) })}</div></div>
      <section class="sec"><div class="sh"><h2>${looks.length} looks, one mechanism.</h2></div>
        <div class="looks">${looks.map((l, k) => `<div class="look"><b>${String(k + 1).padStart(2, '0')} / ${LOOK_NAMES[l]}</b><span>${l === 'original' ? 'The first design' : LOOK_LINES[l]}</span></div>`).join('')}</div>
      </section>
      <section class="sec"><div class="sh"><h2>Bring it into your project.</h2></div>
        <p>Paste the snippet into any page. It carries the Feel engine, the ${esc(p.name.toLowerCase())} and the look you picked above. For iPhone and iPad, add the SwiftUI file to your app.</p>
      </section>
      <section class="sec"><div class="sh"><h2>How it behaves.</h2></div><dl class="behave">${p.behaviors.map(([t, x]) => `<div><dt>${esc(t)}</dt><dd>${esc(x)}</dd></div>`).join('')}</dl></section>
      <nav class="pager"><a href="${ROUTES[prev.tag].path}" data-tag="${prev.tag}"><span class="small">Previous</span><b>${esc(prev.name)}</b></a><a href="${ROUTES[next.tag].path}" data-tag="${next.tag}"><span class="small">Next</span><b>${esc(next.name)}</b></a></nav>
  </main>`;
  const image = card(s.slug);
  out.set(`${s.slug}.html`, pageWith(head({
    ...r, image, imageAlt: `${p.name}, a ${p.kind.toLowerCase()} from ${cfg.name}, in the ${LOOK_NAMES[looks[0]]} look`,
    jsonld: [
      code(p.name, s.description, r.path, image),
      breadcrumbs([['Components', '/'], ...(h ? [[h.name, h.path]] : []), [p.name, r.path]]),
    ],
  }), '<main id="home" hidden></main>', detail));
});

// ── One page per hub: the home's shell with its own heading, copy and grid. ──
for (const h of HUBS) {
  const main = `<main id="home">
    <nav class="crumbs"><a href="/#components" data-tag="" data-anchor="components">Components</a><span>›</span><span>${esc(h.name)}</span></nav>
    <div class="dhead"><h1>${esc(h.name)}</h1><p>${esc(h.intro)}</p></div>
    <div class="grid">${grid(h.parts)}</div>
    <section class="sec"><a class="btn" href="/#components" data-tag="" data-anchor="components">See every control →</a></section>
  </main>`;
  const image = card(h.slug);
  out.set(`${h.slug}.html`, pageWith(head({
    ...ROUTES[`hub:${h.slug}`], image, imageAlt: `${h.name} from ${cfg.name}: ${h.parts.map(p => p.name).join(', ')}`,
    jsonld: [
      { '@context': 'https://schema.org', '@type': 'CollectionPage', name: h.name, description: h.description, url: url(h.path), isPartOf: site, ...(image && { image }),
        mainEntity: { '@type': 'ItemList', itemListElement: h.parts.map((p, k) => ({ '@type': 'ListItem', position: k + 1, url: url(ROUTES[p.tag].path), name: p.name })) } },
      breadcrumbs([['Components', '/'], [h.name, h.path]]),
    ],
  }), main, '<main id="detail" hidden></main>'));
}

// ── 404: a small page of its own, not indexed. ──
out.set('404.html', `<!doctype html>
<html lang="en">
${MARK}
<meta charset="utf-8">
<title>${esc(title('Page not found'))}</title>
<meta name="robots" content="noindex">
<meta name="viewport" content="width=device-width, initial-scale=1">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<style>
:root { --bg: #f6f6f5; --ink: #1d1d1f; --muted: #75757a; --line: #e3e3e1 }
@media (prefers-color-scheme: dark) { :root { --bg: #0b0b0c; --ink: #ededee; --muted: #8b8b90; --line: #222225 } }
body { margin: 0; background: var(--bg); color: var(--ink); font: 400 16px/1.55 system-ui, -apple-system, "Helvetica Neue", sans-serif }
main { max-width: 640px; margin: 0 auto; padding: 18vh 16px 80px }
h1 { margin: 0 0 12px; font-weight: 300; font-size: clamp(36px, 7vw, 56px); letter-spacing: -.04em; line-height: 1 }
p { color: var(--muted); margin: 0 0 32px } a { color: inherit }
ul { list-style: none; padding: 0; margin: 0; border-top: 1px solid var(--line) } li { border-bottom: 1px solid var(--line) }
li a { display: flex; justify-content: space-between; gap: 16px; padding: 12px 0; text-decoration: none } li span { color: var(--muted) }
</style>
<main>
  <h1>Nothing at this notch.</h1>
  <p>This page doesn’t exist. <a href="/">Go to ${esc(cfg.name)}</a>, or open a control:</p>
  <ul>${PARTS.map(p => `<li><a href="${ROUTES[p.tag].path}">${esc(p.name)}<span>${esc(p.kind)}</span></a></li>`).join('')}</ul>
</main>
</html>
`);

// ── Sitemap, robots, llms.txt ──
const indexable = [['/', 'index.html', 'home'], ...PARTS.map(p => [ROUTES[p.tag].path, `${cfg.parts[p.tag].slug}.html`, cfg.parts[p.tag].slug]), ...HUBS.map(h => [h.path, `${h.slug}.html`, h.slug])];
out.set('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
${MARK}
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${indexable.map(([path]) => `  <url><loc>${url(path)}</loc>${lastmod ? `<lastmod>${lastmod}</lastmod>` : ''}</url>`).join('\n')}
</urlset>
`);
out.set('sitemap-images.xml', `<?xml version="1.0" encoding="UTF-8"?>
${MARK}
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${indexable.filter(([, , c]) => card(c)).map(([path, , c]) => `  <url><loc>${url(path)}</loc><image:image><image:loc>${card(c)}</image:loc></image:image></url>`).join('\n')}
</urlset>
`);
out.set('robots.txt', `${MARK_TXT}
User-agent: *
Allow: /
Disallow: /api/

Sitemap: ${url('/sitemap.xml')}
Sitemap: ${url('/sitemap-images.xml')}
`);
out.set('llms.txt', `# ${cfg.name}

> ${cfg.home.description} Each control is one web component with no dependencies, with a SwiftUI version for iPhone and iPad, in several looks, light and dark.

## Controls

${PARTS.map(p => `- [${p.name}](${url(ROUTES[p.tag].path)}): ${p.note}`).join('\n')}

## Links

- [Source on GitHub](${cfg.repo}) (${cfg.license})
- [${cfg.studio.name}](${cfg.studio.url}), the studio that makes ${cfg.name}
`);

// ── Write, or check ──
const generated = name => { try { const t = readFileSync(at('site', name), 'utf8'); return t.includes(MARK) || t.startsWith(MARK_TXT); } catch { return false; } };
if (CHECK) {
  for (const [name, body] of out) {
    if (!existsSync(at('site', name))) errors.push(`site/${name} is missing: run npm run build`);
    else if (readFileSync(at('site', name), 'utf8') !== body) errors.push(`site/${name} is out of date: run npm run build`);
  }
  for (const f of readdirSync(at('site'))) if (!out.has(f) && generated(f)) errors.push(`site/${f} was generated but no page makes it any more: run npm run build`);
} else {
  for (const f of readdirSync(at('site'))) if (!out.has(f) && generated(f)) { unlinkSync(at('site', f)); console.log(`removed site/${f}`); }
  mkdirSync(at('site'), { recursive: true });
  for (const [name, body] of out) writeFileSync(at('site', name), body);
}

// ── The rules every indexable page must keep (tools/seo/SEO.md) ──
const seen = { titles: new Map(), descriptions: new Map() };
for (const [path, name] of indexable) {
  const html = out.get(name), where = `site/${name}`;
  const t = html.match(/<title>([^<]*)<\/title>/)?.[1], d = html.match(/<meta name="description" content="([^"]*)">/)?.[1];
  if (!t) errors.push(`${where}: no <title>`); else {
    if (plain(t).length > 60) errors.push(`${where}: title is ${plain(t).length} characters, over 60: "${plain(t)}"`);
    if (!plain(t).endsWith(` · ${cfg.name}`)) errors.push(`${where}: title should end with " · ${cfg.name}"`);
    if (seen.titles.has(t)) errors.push(`${where}: same title as ${seen.titles.get(t)}`); seen.titles.set(t, where);
  }
  if (!d) errors.push(`${where}: no meta description`); else {
    if (plain(d).length > 160) errors.push(`${where}: description is ${plain(d).length} characters, over 160`);
    if (seen.descriptions.has(d)) errors.push(`${where}: same description as ${seen.descriptions.get(d)}`); seen.descriptions.set(d, where);
  }
  if (!html.includes(`<link rel="canonical" href="${url(path)}">`)) errors.push(`${where}: canonical is not ${url(path)}`);
  const h1s = html.replace(/<script[\s\S]*?<\/script>/g, '').match(/<h1[\s>]/g) || [];
  if (h1s.length !== 1) errors.push(`${where}: ${h1s.length} <h1> in the static HTML, want exactly 1`);
  for (const [, img] of html.matchAll(/<meta (?:property="og:image"|name="twitter:image") content="([^"]+)">/g)) {
    if (!img.startsWith(ORIGIN + '/') || !existsSync(at('site', img.slice(ORIGIN.length)))) errors.push(`${where}: share image ${img} has no file in site/`);
  }
  if (!/property="og:image"/.test(html)) warnings.push(`${where}: no share card yet (node tools/seo/og.mjs, then build again)`);
  for (const [, j] of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    let data; try { data = JSON.parse(j); } catch (e) { errors.push(`${where}: JSON-LD does not parse: ${e.message}`); continue; }
    const s = JSON.stringify(data);
    if (/aggregateRating|"review"|"offers"/i.test(s)) errors.push(`${where}: JSON-LD states ratings, reviews or offers; Detent states only what the page shows`);
    if (data['@type'] === 'FAQPage') {
      const visible = [...html.matchAll(/<details><summary>([\s\S]*?)<\/summary><p>([\s\S]*?)<\/p><\/details>/g)].map(([, q, a]) => plain(q) + '|' + plain(a)).join('\n');
      const stated = data.mainEntity.map(q => q.name + '|' + q.acceptedAnswer.text).join('\n');
      if (visible !== stated) errors.push(`${where}: the FAQPage JSON-LD differs from the visible questions`);
    }
  }
  for (const [, href] of html.replace(/<script[\s\S]*?<\/script>/g, '').matchAll(/<a [^>]*href="(\/[^"#]*)/g)) {
    if (!indexable.some(([p]) => p === href)) errors.push(`${where}: link to ${href}, which no page serves`);
  }
}
for (const [, img] of out.get('sitemap-images.xml').matchAll(/<image:loc>([^<]+)<\/image:loc>/g)) {
  if (!img.startsWith(ORIGIN + '/') || !existsSync(at('site', img.slice(ORIGIN.length)))) errors.push(`site/sitemap-images.xml: image ${img} has no file in site/`);
}
for (const [name, body] of out) {
  if (!name.endsWith('.html')) continue;
  for (const [, href] of body.matchAll(/<link rel="(?:icon|apple-touch-icon)"[^>]* href="(\/[^"]*)"/g)) {
    if (!existsSync(at('site', href))) errors.push(`site/${name}: icon ${href} has no file in site/`);
  }
}
finish();

function finish() {
  for (const w of warnings) console.warn('warning: ' + w);
  for (const e of errors) console.error('error: ' + e);
  if (errors.length) { console.error(`${errors.length} error${errors.length > 1 ? 's' : ''}${CHECK ? '' : ' (site/ was written; fix and build again)'}`); process.exit(1); }
  if (!CHECK) console.log(`site/: home, ${PARTS.length} control pages, ${HUBS.length} hubs, 404, sitemap.xml, sitemap-images.xml, robots.txt, llms.txt (${blocks.length} control scripts, ${swift.length} SwiftUI files)`);
  else console.log(`check: ${indexable.length} indexable pages pass${warnings.length ? `, ${warnings.length} warning${warnings.length > 1 ? 's' : ''}` : ''}`);
  process.exit(0);
}
